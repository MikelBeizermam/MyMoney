"""Generates web/src/lib/classifierRules.ts from the iOS CategoryClassifier.swift,
so the web app and the iOS app classify merchants identically.
Run: python3 web/scripts/gen-classifier.py"""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
swift = (root / "MyMoney/Services/CategoryClassifier.swift").read_text(encoding="utf-8")
body = swift.split("let rules:", 1)[1].split("for (category, keywords)", 1)[0]
body = "\n".join(l.split("//", 1)[0] if not l.strip().startswith("//") else "" for l in body.splitlines())
rules = []
for m in re.finditer(r"\(\.(\w+),\s*\[(.*?)\]\)", body, re.S):
    words = [json.loads('"' + w + '"') for w in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))]
    rules.append((m.group(1), words))
out = ["// AUTO-GENERATED by web/scripts/gen-classifier.py from CategoryClassifier.swift – do not edit.",
       "import type { CategoryKey } from './types'", "",
       "export const CLASSIFIER_RULES: [CategoryKey, string[]][] = ["]
for cat, words in rules:
    out.append(f"  [{json.dumps(cat)}, {json.dumps(words, ensure_ascii=False)}],")
out.append("]\n")
dest = root / "web/src/lib/classifierRules.ts"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out), encoding="utf-8")
print(f"{len(rules)} categories, {sum(len(w) for _, w in rules)} keywords -> {dest.relative_to(root)}")
